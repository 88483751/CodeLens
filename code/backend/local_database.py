"""PostgreSQL storage shared by the local workbench entry points."""

from contextlib import contextmanager
import os

import psycopg
from psycopg.rows import dict_row


DSN_ENV = "CODELENS_LOCAL_DATABASE_URL"
_WRITE_LOCK = 18766

_SCHEMA = """
CREATE TABLE IF NOT EXISTS project (
    id TEXT PRIMARY KEY, name TEXT NOT NULL,
    created TEXT DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS version (
    project_id TEXT REFERENCES project(id) ON DELETE CASCADE,
    digest TEXT, files TEXT NOT NULL, PRIMARY KEY(project_id, digest)
);
CREATE TABLE IF NOT EXISTS analysis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id TEXT NOT NULL,
    version TEXT NOT NULL,
    created TEXT DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    report TEXT NOT NULL, changes TEXT NOT NULL, issues TEXT NOT NULL,
    ai TEXT, ai_status TEXT NOT NULL DEFAULT 'not_run',
    FOREIGN KEY(project_id, version) REFERENCES version(project_id, digest) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS analysis_project ON analysis(project_id, id);
CREATE TABLE IF NOT EXISTS project_checkpoint (
    project_id TEXT REFERENCES project(id) ON DELETE CASCADE,
    fingerprint TEXT, data TEXT NOT NULL, updated DOUBLE PRECISION NOT NULL,
    PRIMARY KEY(project_id, fingerprint)
);
CREATE TABLE IF NOT EXISTS review_checkpoint (
    fingerprint TEXT PRIMARY KEY,
    payload TEXT NOT NULL,
    updated DOUBLE PRECISION NOT NULL
);
"""


@contextmanager
def connect(dsn, *, write=False):
    with psycopg.connect(dsn, row_factory=dict_row, connect_timeout=5) as db:
        if write:
            # Keep analysis baselines and checkpoint pruning consistent across processes.
            db.execute("SELECT pg_advisory_xact_lock(%s)", (_WRITE_LOCK,))
        yield db


def initialize(dsn):
    with connect(dsn, write=True) as db:
        db.execute(_SCHEMA)


def start_database():
    dsn = os.environ.get(DSN_ENV)
    if not dsn:
        raise SystemExit(f"请先配置 {DSN_ENV}，指向本机版的 PostgreSQL 数据库。")
    try:
        initialize(dsn)
    except psycopg.Error:
        raise SystemExit("无法初始化本机 PostgreSQL。请检查连接配置、数据库服务和建表权限。") from None
    return dsn
